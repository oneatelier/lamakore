#!/usr/bin/env node
/*
 * Design-token codegen (P007): artifacts/design-tokens.json is the source of
 * truth. Emits CSS custom properties (per-theme [data-theme] blocks) and a
 * frozen typed TS object. Font faces, focus-ring behavior, and the
 * reduced-motion transform swap live here so components never hardcode them.
 * Usage: node scripts/tokens-codegen.mjs [--check]
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const TOKENS = path.join(root, 'artifacts', 'design-tokens.json');
const OUT_DIR = path.join(root, 'packages', 'ui', 'src', 'tokens');

const HEADER = (name) =>
  `/* DO NOT EDIT — generated by scripts/tokens-codegen.mjs from artifacts/design-tokens.json (${name}). */\n`;

function cssVarBlock(theme) {
  const lines = [];
  for (const [k, v] of Object.entries(theme.colors)) {
    lines.push(`  --${k}: ${v.hex};`);
  }
  return lines.join('\n');
}

function buildCss(t) {
  const themes = Object.entries(t.themes);
  let css = HEADER('generated.css');
  css += `/* Art direction: Brass & Void. Never the purple/cyan gradient. */\n`;
  css += `@font-face {\n  font-family: "Fraunces";\n  src: url("/assets/fonts/fraunces/Fraunces-Variable.ttf") format("truetype-variations");\n  font-weight: 100 900;\n  font-display: swap;\n}\n`;
  css += `@font-face {\n  font-family: "Inter";\n  src: url("/assets/fonts/inter/Inter-Variable.ttf") format("truetype-variations");\n  font-weight: 100 900;\n  font-display: swap;\n}\n`;
  css += `@font-face {\n  font-family: "JetBrains Mono";\n  src: url("/assets/fonts/jetbrainsmono/JetBrainsMono-Variable.ttf") format("truetype-variations");\n  font-weight: 100 900;\n  font-display: swap;\n}\n`;
  const [firstName, firstTheme] = themes[0];
  css += `:root, [data-theme="${firstName}"] {\n${cssVarBlock(firstTheme)}\n`;
  css += `  --font-display: "Fraunces", Georgia, serif;\n  --font-ui: "Inter", system-ui, sans-serif;\n  --font-mono: "JetBrains Mono", ui-monospace, monospace;\n`;
  for (const [k, v] of Object.entries(t.radii)) css += `  --radius-${k}: ${v === 999 ? '999px' : `${v}px`};\n`;
  for (const [k, v] of Object.entries(t.spacing)) css += `  --space-${k}: ${v}px;\n`;
  for (const [k, v] of Object.entries(t.elevation)) {
    css += `  --elevation-${k}-shadow: ${v.shadow};\n  --elevation-${k}-inner: ${v.inner};\n`;
  }
  for (const [k, v] of Object.entries(t.type.scale)) css += `  --text-${k}: ${v}px;\n`;
  for (const [k, v] of Object.entries(t.motion.durations)) css += `  --duration-${k}: ${v}ms;\n`;
  for (const [k, v] of Object.entries(t.motion.easings)) css += `  --easing-${k}: ${v};\n`;
  for (const [k, v] of Object.entries(t.motion.springs)) {
    css += `  --spring-${k}-stiffness: ${v.stiffness};\n  --spring-${k}-damping: ${v.damping};\n`;
  }
  css += `}\n`;
  for (const [name, theme] of themes.slice(1)) {
    css += `[data-theme="${name}"] {\n${cssVarBlock(theme)}\n}\n`;
  }
  css += `:focus { outline: none; }\n`;
  css += `:focus-visible { outline: 2px solid var(--focus-ring); outline-offset: 2px; }\n`;
  css += `.reduced-motion *, .reduced-motion *::before, .reduced-motion *::after {\n  animation-duration: 1ms !important;\n  transition-duration: 120ms !important;\n  transition-property: opacity !important;\n}\n`;
  return css;
}

function buildTs(t) {
  const ts = (v) => JSON.stringify(v);
  let out = `// DO NOT EDIT — generated by scripts/tokens-codegen.mjs from artifacts/design-tokens.json (generated.ts).\n`;
  out += `export const THEMES = Object.freeze({\n`;
  for (const [name, theme] of Object.entries(t.themes)) {
    out += `  ${ts(name)}: Object.freeze({\n    kind: ${ts(theme.kind)},\n    label: ${ts(theme.label)},\n    colors: Object.freeze({\n`;
    for (const [k, v] of Object.entries(theme.colors)) {
      out += `      ${ts(k)}: ${ts(v.hex)},\n`;
    }
    out += `    }),\n  }),\n`;
  }
  out += `} as const);\n\nexport type ThemeName = keyof typeof THEMES;\n`;
  out += `export const RADII = Object.freeze(${JSON.stringify(t.radii)} as const);\n`;
  out += `export const SPACING = Object.freeze(${JSON.stringify(t.spacing)} as const);\n`;
  out += `export const ELEVATION = Object.freeze(${JSON.stringify(t.elevation)} as const);\n`;
  out += `export const TYPE_SCALE = Object.freeze(${JSON.stringify(t.type.scale)} as const);\n`;
  out += `export const TYPE_FAMILIES = Object.freeze(${JSON.stringify(t.type.families)} as const);\n`;
  out += `export const DURATIONS = Object.freeze(${JSON.stringify(t.motion.durations)} as const);\n`;
  out += `export const EASINGS = Object.freeze(${JSON.stringify(t.motion.easings)} as const);\n`;
  out += `export const SPRINGS = Object.freeze(${JSON.stringify(t.motion.springs)} as const);\n`;
  out += `export const SETTLE_MAX_MS = ${t.motion.settle_max_ms} as const;\n`;
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const t = JSON.parse(readFileSync(TOKENS, 'utf8'));
  const files = {
    'generated.css': buildCss(t),
    'generated.ts': buildTs(t),
  };
  let stale = [];
  for (const [name, text] of Object.entries(files)) {
    const abs = path.join(OUT_DIR, name);
    if (check) {
      let cur = null;
      try {
        cur = readFileSync(abs, 'utf8');
      } catch {
        cur = null;
      }
      if (cur !== text) stale.push(name);
    } else {
      mkdirSync(OUT_DIR, { recursive: true });
      writeFileSync(abs, text, 'utf8');
      console.log(`wrote packages/ui/src/tokens/${name}`);
    }
  }
  if (check) {
    if (stale.length > 0) {
      console.error(`stale token outputs: ${stale.join(', ')}; run node scripts/tokens-codegen.mjs`);
      process.exitCode = 1;
    } else {
      console.log('token outputs are current.');
    }
  }
}

main();
